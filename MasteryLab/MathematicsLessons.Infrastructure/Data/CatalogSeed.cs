                    Id = lessonId,
                    LevelId = levelId,
                    TopicId = t.Id,
                    Title = title,
                    Content =
                        $"Урок: {title}.\n\n" +
                        "1) Гледай видеото докрай.\n" +
                        "2) Преговори основните понятия.\n" +
                        "3) Реши упражненията — при грешка гледай урока отново.\n" +
                        "4) След успех се отключва следващият урок.",
                    Video = VideoFor(lessonId),
                    SortOrder = order++,
                    DurationMinutes = 15,
                    PointsReward = 25
                });
                foreach (var (q, sol, hint, pts) in BuildExercises(levelId, title))
                {
                    exercises.Add(new Exercise
                    {
                        Id = eid++,
                        LessonId = lessonId,
                        Question = q,
                        Solution = sol,
                        Hint = hint,
                        PointsReward = pts
                    });
                }
            }
        }

